#ifndef SHOOT_H
#define SHOOT_H

/**
 * @file shoot.h
 * @brief 发射机构控制模块接口定义
 * 
 * @details 本模块负责机器人发射机构的控制，包括：
 *          - 双摩擦轮速度控制（左右摩擦轮协同驱动弹丸）
 *          - 拨盘电机控制（单发、连发、反转等多种模式）
 *          - 弹速设定和热量管理
 *          - 堵转检测和保护机制
 * 
 * @note 发射模块通过消息中心与 cmd 模块通信，不直接处理遥控输入
 */

/**
 * @brief 发射机构初始化函数
 * 
 * @details 初始化流程：
 *          1. 配置并初始化左摩擦轮电机（M3508，CAN3 ID=1）
 *          2. 配置并初始化右摩擦轮电机（M3508，CAN3 ID=8）
 *          3. 配置并初始化拨盘电机（M2006，CAN1 ID=3）
 *          4. 注册消息发布者和订阅者
 * 
 * @note 该函数会被 RobotInit() 调用，无需手动执行
 * @see RobotInit()
 */
void ShootInit();

/**
 * @brief 发射控制任务主循环
 * 
 * @details 任务执行流程：
 *          1. 从消息总线订阅发射控制指令（包含射击模式、弹速设定、拨盘模式等）
 *          2. 根据射击模式执行控制逻辑：
 *             - SHOOT_OFF: 紧急停止，关闭所有电机
 *             - 正常运行：根据指令控制摩擦轮和拨盘
 *          3. 摩擦轮控制：
 *             - 开启时根据目标弹速设置参考转速（支持多档弹速）
 *             - 关闭时停止摩擦轮
 *          4. 拨盘控制（多种模式）：
 *             - LOAD_STOP: 停止拨盘
 *             - LOAD_1_BULLET: 单发模式（能量机关/英雄射击）
 *             - LOAD_3_BULLET: 三连发模式
 *             - LOAD_BURSTFIRE: 连发模式（可变射频）
 *             - LOAD_REVERSE: 反转模式（退弹/排除卡弹）
 *          5. 堵转检测和保护：
 *             - 监测拨盘电流，超过阈值时自动反转
 *             - 记录堵转次数，防止连续堵转
 *          6. 热量管理：
 *             - 根据裁判系统反馈的剩余热量限制发射
 *             - 热量不足时强制停止拨盘
 *          7. 发布发射状态反馈
 * 
 * @note 该任务应在 FreeRTOS 中作为独立任务运行
 * @note 单发和三连发模式包含冷却时间（dead_time），防止连续触发
 * @see ShootInit()
 */
void ShootTask();

#endif // SHOOT_H